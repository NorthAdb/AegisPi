import type { DatabaseSync } from "node:sqlite";
import { canonicalJson, sha256Hex } from "../../governance/canonical.ts";
import { withImmediateTx, writeAuditEvent } from "../../governance/db.ts";
import { checkSourceReadAuthorized, grantSourceRead } from "../../governance/policy.ts";

export interface SkillScriptRef {
  scriptId: string;
  name: string;
  description: string;
  runtime: "node";
  scriptSha256: string;
  reviewedBy: string;
  /** Human-reviewed deterministic script body executed ONLY in no-net zero-credential sandbox after independent auth. */
  sourceCode: string;
}

export interface SkillRow {
  skill_id: string;
  name: string;
  summary: string;
  active_version: number;
  state: "ACTIVE" | "REVOKED";
  revoked_at: number | null;
  revoke_reason: string | null;
  created_at: number;
  updated_at: number;
}

export interface SkillVersionRow {
  skill_id: string;
  version: number;
  summary: string;
  body: string;
  body_sha256: string;
  scripts_json: string;
  reviewed_by: string;
  created_at: number;
}

export interface SkillIndexEntry {
  skillId: string;
  name: string;
  summary: string;
  version: number;
  state: "ACTIVE" | "REVOKED";
  scriptCount: number;
  versions: number[];
}

export interface LockedSkillSet {
  skillSetHash: string;
  skills: Array<{ skillId: string; name: string; summary: string; version: number }>;
  renderedL1Index: string;
}

