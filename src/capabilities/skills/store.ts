export function registerSkillVersion(
  db: DatabaseSync,
  params: {
    skillId: string;
    name: string;
    version: number;
    summary: string;
    body: string;
    scripts?: Array<Omit<SkillScriptRef, "scriptSha256"> & { scriptSha256?: string }>;
    reviewedBy: string;
    activate?: boolean;
    now: number;
  },
): { skill: SkillRow; version: SkillVersionRow } {
  const normalizedScripts: SkillScriptRef[] = (params.scripts ?? []).map((s) => {
    const computed = sha256Hex(s.sourceCode);
    if (s.scriptSha256 && s.scriptSha256.toLowerCase() !== computed.toLowerCase()) {
      throw new Error(`Skill script ${s.scriptId} SHA-256 mismatch: expected ${s.scriptSha256}, computed ${computed}`);
    }
    return {
      scriptId: s.scriptId,
      name: s.name,
      description: s.description,
      runtime: s.runtime,
      scriptSha256: computed,
      reviewedBy: s.reviewedBy,
      sourceCode: s.sourceCode,
    };
  });
  const bodySha256 = sha256Hex(params.body);

  return withImmediateTx(db, () => {
    const existing = db.prepare("SELECT * FROM skills WHERE skill_id = ?").get(params.skillId) as
      | SkillRow
      | undefined;
    if (!existing) {
      db.prepare(
        `INSERT INTO skills(skill_id, name, summary, active_version, state, revoked_at, revoke_reason, created_at, updated_at)
         VALUES (?, ?, ?, ?, 'ACTIVE', NULL, NULL, ?, ?)`,
      ).run(params.skillId, params.name, params.summary, params.version, params.now, params.now);
    } else if (params.activate !== false) {
      db.prepare(
        `UPDATE skills
            SET name = ?, summary = ?, active_version = ?, state = 'ACTIVE', revoked_at = NULL, revoke_reason = NULL, updated_at = ?
          WHERE skill_id = ?`,
      ).run(params.name, params.summary, params.version, params.now, params.skillId);
    }

    db.prepare(
      `INSERT INTO skill_versions(skill_id, version, summary, body, body_sha256, scripts_json, reviewed_by, created_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)
       ON CONFLICT(skill_id, version) DO UPDATE SET
         summary = excluded.summary,
         body = excluded.body,
         body_sha256 = excluded.body_sha256,
         scripts_json = excluded.scripts_json,
         reviewed_by = excluded.reviewed_by`,
    ).run(
      params.skillId,
      params.version,
      params.summary,
      params.body,
      bodySha256,
      JSON.stringify(normalizedScripts),
      params.reviewedBy,
      params.now,
    );

    writeAuditEvent(db, {
      entityType: "skill",
      entityId: params.skillId,
      eventKey: `register:${params.skillId}:v${params.version}:${bodySha256.slice(0, 12)}`,
      eventType: "skill_version_registered",
      occurredAt: params.now,
      details: {
        skillId: params.skillId,
        version: params.version,
        bodySha256,
        scriptIds: normalizedScripts.map((s) => ({ scriptId: s.scriptId, sha256: s.scriptSha256 })),
        reviewedBy: params.reviewedBy,
      },
    });

    const skill = db.prepare("SELECT * FROM skills WHERE skill_id = ?").get(params.skillId) as unknown as SkillRow;
    const version = db
      .prepare("SELECT * FROM skill_versions WHERE skill_id = ? AND version = ?")
      .get(params.skillId, params.version) as unknown as SkillVersionRow;
    return { skill, version };
  });
}

/**
 * Seeds the built-in 3-level Stage 2 skill ("weekly-brief-helper") idempotently if absent.
 * Grants ONLY L2 `read_body` for the default principal/scope if provided; L3 `execute_script`
 * is NEVER granted by default and requires explicit independent authorization.
 */
export function ensureDefaultStage2Skills(
  db: DatabaseSync,
  now: number,
  opts?: { defaultPrincipalId?: string; defaultScopeId?: string },
): void {
  const existing = db.prepare("SELECT skill_id FROM skills WHERE skill_id = ?").get("weekly-brief-helper");
  if (!existing) {
    registerSkillVersion(db, {
      skillId: "weekly-brief-helper",
      name: "Weekly Brief & Schedule Diff Helper",
      version: 1,
      summary: "Compare email updates and repository milestones, draft structured status replies, and run an audited summary formatter.",
      body: [
        "# Weekly Brief & Schedule Diff Helper (v1)",
        "",
        "## Level 2 Instructions (On-Demand Disclosure)",
        "1. Read authorized project memory notes first to identify the target repository and milestone dates.",
        "2. Fetch only the authorized latest email via read-only IMAP (BODY.PEEK) and authorized repo files via pinned GitHub MCP.",
        "3. List every date or milestone mismatch clearly with source citations (UID + repo ref/path).",
        "4. If an outbound email reply is requested, draft a concise plain-text reply and park for explicit Tier 2 approval.",
        "5. For batch formatting, invoke the reviewed L3 script `format-weekly-brief` in the no-net sandbox after independent authorization.",
      ].join("\n"),
      scripts: [
        {
          scriptId: "format-weekly-brief",
          name: "format-weekly-brief.cjs",
          description: "Deterministic no-net Node formatter that renders a reconciled markdown weekly brief into /out.",
          runtime: "node",
          scriptSha256: DEFAULT_WEEKLY_BRIEF_SCRIPT_SHA256,
          reviewedBy: "host-security-review",
          sourceCode: DEFAULT_WEEKLY_BRIEF_SCRIPT_CODE,
        },
      ],
      reviewedBy: "host-security-review",
      activate: true,
      now,
    });
  }
  if (opts?.defaultPrincipalId && opts?.defaultScopeId) {
    const existingGrant = db
      .prepare(
        `SELECT grant_id FROM source_read_grants
          WHERE principal_id = ? AND scope_id = ? AND source_type = 'skill' AND resource_id = 'skill:weekly-brief-helper'
          LIMIT 1`,
      )
      .get(opts.defaultPrincipalId, opts.defaultScopeId);
    if (!existingGrant) {
      grantSourceRead(db, {
        principalId: opts.defaultPrincipalId,
        scopeId: opts.defaultScopeId,
        sourceType: "skill",
        resourceId: "skill:weekly-brief-helper",
        operations: ["read_body"],
        now,
      });
    }
  }
}

export function listSkillsIndex(db: DatabaseSync): SkillIndexEntry[] {
  const skills = db.prepare("SELECT * FROM skills ORDER BY skill_id ASC").all() as unknown as SkillRow[];
  return skills.map((s) => {
    const versionRows = db
      .prepare("SELECT version, scripts_json FROM skill_versions WHERE skill_id = ? ORDER BY version ASC")
      .all(s.skill_id) as Array<{ version: number; scripts_json: string }>;
    const activeRow = versionRows.find((v) => v.version === s.active_version);
    let scriptCount = 0;
    if (activeRow) {
      try {
        const parsed = JSON.parse(activeRow.scripts_json) as unknown[];
        scriptCount = Array.isArray(parsed) ? parsed.length : 0;
      } catch {
        scriptCount = 0;
      }
    }
    return {
      skillId: s.skill_id,
      name: s.name,
      summary: s.summary,
      version: s.active_version,
      state: s.state,
      scriptCount,
      versions: versionRows.map((v) => v.version),
    };
  });
}

export function computeActiveSkillSetHash(db: DatabaseSync): LockedSkillSet {
  const active = db
    .prepare("SELECT skill_id, name, summary, active_version FROM skills WHERE state = 'ACTIVE' ORDER BY skill_id ASC")
    .all() as Array<{ skill_id: string; name: string; summary: string; active_version: number }>;
  const items = active.map((a) => ({
    skillId: a.skill_id,
    name: a.name,
    summary: a.summary,
    version: a.active_version,
  }));
  const skillSetHash = sha256Hex(canonicalJson(items));
  const renderedL1Index =
    items.length === 0
      ? ""
      : [
          `# Active Skills Index (L1 Disclosure Only, skill_set_hash=${skillSetHash.slice(0, 12)})`,
          ...items.map((i) => `- [${i.skillId} v${i.version}] ${i.name}: ${i.summary}`),
        ].join("\n");
  return { skillSetHash, skills: items, renderedL1Index };
}

/**
 * Locks the active task/run's skill_set_hash (S2-P1-2: keyed by lockKey = conversation+run so
 * in-flight tasks stay locked while subsequent new tasks in the SAME conversation get updated versions!),
 * while dynamically excluding any skill that has been REVOKED since lock time.
 */
export function getOrLockConversationSkillSet(
  db: DatabaseSync,
  params: { runtimeEpoch: string; conversationId: string; lockKey?: string; now: number },
): LockedSkillSet {
  const effectiveLockKey = params.lockKey ?? params.conversationId;
  const existing = db
    .prepare(
      "SELECT skill_set_hash, locked_skills_json FROM conversation_skill_locks WHERE runtime_epoch = ? AND conversation_id = ?",
    )
    .get(params.runtimeEpoch, effectiveLockKey) as
    | { skill_set_hash: string; locked_skills_json: string }
    | undefined;

  if (!existing) {
    const computed = computeActiveSkillSetHash(db);
    withImmediateTx(db, () => {
      db.prepare(
        `INSERT OR IGNORE INTO conversation_skill_locks(runtime_epoch, conversation_id, skill_set_hash, locked_skills_json, created_at)
         VALUES (?, ?, ?, ?, ?)`,
      ).run(
        params.runtimeEpoch,
        effectiveLockKey,
        computed.skillSetHash,
        JSON.stringify(computed.skills),
        params.now,
      );
    });
    return computed;
  }

  const locked = JSON.parse(existing.locked_skills_json) as Array<{
    skillId: string;
    name: string;
    summary: string;
    version: number;
  }>;
  const liveStates = new Map<string, string>();
  for (const row of db.prepare("SELECT skill_id, state FROM skills").all() as Array<{ skill_id: string; state: string }>) {
    liveStates.set(row.skill_id, row.state);
  }
  const activeLocked = locked.filter((s) => liveStates.get(s.skillId) === "ACTIVE");
  const renderedL1Index =
    activeLocked.length === 0
      ? ""
      : [
          `# Active Skills Index (L1 Disclosure Only, skill_set_hash=${existing.skill_set_hash.slice(0, 12)})`,
          ...activeLocked.map((i) => `- [${i.skillId} v${i.version}] ${i.name}: ${i.summary}`),
        ].join("\n");
  return {
    skillSetHash: existing.skill_set_hash,
    skills: activeLocked,
    renderedL1Index,
  };
}

/**
 * Level 2 on-demand body disclosure + Level 3 reviewed script metadata (hash + description, without executing).
 * S2-P0-3d: Enforces live principal+scope `skill` `read_body` authorization AND refuses immediately if REVOKED.
 */
export function readSkillDisclosure(
  db: DatabaseSync,
  params: {
    skillId: string;
    principalId: string;
    scopeId: string;
    runtimeEpoch?: string;
    conversationId?: string;
    lockKey?: string;
    requestedVersion?: number;
  },
):
  | {
      ok: true;
      skillId: string;
      name: string;
      version: number;
      summary: string;
      body: string;
      bodySha256: string;
      scripts: Array<{
        scriptId: string;
        name: string;
        description: string;
        runtime: "node";
        scriptSha256: string;
        reviewedBy: string;
      }>;
    }
  | { ok: false; code: string; reason: string } {
  const auth = checkSourceReadAuthorized(db, {
    principalId: params.principalId,
    scopeId: params.scopeId,
    sourceType: "skill",
    resourceId: `skill:${params.skillId}`,
    operation: "read_body",
  });
  if (!auth.ok) {
    return {
      ok: false,
      code: "skill_read_denied",
      reason: `Principal ${params.principalId} lacks active read_body authorization for skill ${params.skillId} in scope ${params.scopeId}`,
    };
  }

  const skill = db.prepare("SELECT * FROM skills WHERE skill_id = ?").get(params.skillId) as
    | SkillRow
    | undefined;
  if (!skill) {
    return { ok: false, code: "skill_not_found", reason: `Skill not found: ${params.skillId}` };
  }
  if (skill.state === "REVOKED") {
    return {
      ok: false,
      code: "skill_revoked",
      reason: `Skill ${params.skillId} has been revoked (${skill.revoke_reason ?? "revoked"})`,
    };
  }

  let versionToRead = params.requestedVersion ?? skill.active_version;
  const effectiveLockKey = params.lockKey ?? params.conversationId;
  if (params.runtimeEpoch && effectiveLockKey && params.requestedVersion === undefined) {
    const lock = db
      .prepare(
        "SELECT locked_skills_json FROM conversation_skill_locks WHERE runtime_epoch = ? AND conversation_id = ?",
      )
      .get(params.runtimeEpoch, effectiveLockKey) as { locked_skills_json: string } | undefined;
    if (lock) {
      const locked = JSON.parse(lock.locked_skills_json) as Array<{ skillId: string; version: number }>;
      const match = locked.find((l) => l.skillId === params.skillId);
      if (match) {
        versionToRead = match.version;
      }
    }
  }

  const ver = db
    .prepare("SELECT * FROM skill_versions WHERE skill_id = ? AND version = ?")
    .get(params.skillId, versionToRead) as SkillVersionRow | undefined;
  if (!ver) {
    return {
      ok: false,
      code: "skill_version_not_found",
      reason: `Skill ${params.skillId} v${versionToRead} not found`,
    };
  }

  const scripts = (JSON.parse(ver.scripts_json || "[]") as SkillScriptRef[]).map((s) => ({
    scriptId: s.scriptId,
    name: s.name,
    description: s.description,
    runtime: s.runtime,
    scriptSha256: s.scriptSha256,
    reviewedBy: s.reviewedBy,
  }));

  return {
    ok: true,
    skillId: skill.skill_id,
    name: skill.name,
    version: ver.version,
    summary: ver.summary,
    body: ver.body,
    bodySha256: ver.body_sha256,
    scripts,
  };
}

/**
 * Resolves a human-reviewed L3 skill script and verifies:
 * 1. Active `read_body` grant for (principalId, scopeId, skill).
 * 2. Skill is ACTIVE and script integrity SHA-256 matches stored & optional expected hash.
 * 3. Independent active `execute_script` grant for (principalId, scopeId, skill, scriptId, scriptSha256)! (S2-P0-3d)
 */
export function resolveVerifiedSkillScript(
  db: DatabaseSync,
  params: {
    skillId: string;
    scriptId: string;
    principalId: string;
    scopeId: string;
    expectedSha256?: string;
    runtimeEpoch?: string;
    conversationId?: string;
    lockKey?: string;
  },
): { ok: true; script: SkillScriptRef; version: number } | { ok: false; code: string; reason: string } {
  const readAuth = checkSourceReadAuthorized(db, {
    principalId: params.principalId,
    scopeId: params.scopeId,
    sourceType: "skill",
    resourceId: `skill:${params.skillId}`,
    operation: "read_body",
  });
  if (!readAuth.ok) {
    return {
      ok: false,
      code: "skill_read_denied",
      reason: `Principal ${params.principalId} lacks active read_body authorization for skill ${params.skillId}`,
    };
  }

  const skill = db.prepare("SELECT * FROM skills WHERE skill_id = ?").get(params.skillId) as
    | SkillRow
    | undefined;
  if (!skill) {
    return { ok: false, code: "skill_not_found", reason: `Skill not found: ${params.skillId}` };
  }
  if (skill.state === "REVOKED") {
    return { ok: false, code: "skill_revoked", reason: `Skill ${params.skillId} has been revoked` };
  }

  let versionToUse = skill.active_version;
  const effectiveLockKey = params.lockKey ?? params.conversationId;
  if (params.runtimeEpoch && effectiveLockKey) {
    const lock = db
      .prepare(
        "SELECT locked_skills_json FROM conversation_skill_locks WHERE runtime_epoch = ? AND conversation_id = ?",
      )
      .get(params.runtimeEpoch, effectiveLockKey) as { locked_skills_json: string } | undefined;
    if (lock) {
      const locked = JSON.parse(lock.locked_skills_json) as Array<{ skillId: string; version: number }>;
      const match = locked.find((l) => l.skillId === params.skillId);
      if (match) versionToUse = match.version;
    }
  }

  const ver = db
    .prepare("SELECT * FROM skill_versions WHERE skill_id = ? AND version = ?")
    .get(params.skillId, versionToUse) as SkillVersionRow | undefined;
  if (!ver) {
    return { ok: false, code: "skill_version_not_found", reason: `Skill ${params.skillId} v${versionToUse} missing` };
  }
  const scripts = JSON.parse(ver.scripts_json || "[]") as SkillScriptRef[];
  const script = scripts.find((s) => s.scriptId === params.scriptId);
  if (!script) {
    return {
      ok: false,
      code: "skill_script_not_found",
      reason: `Script ${params.scriptId} not found in skill ${params.skillId} v${versionToUse}`,
    };
  }
  const actualSha = sha256Hex(script.sourceCode);
  if (actualSha !== script.scriptSha256) {
    return {
      ok: false,
      code: "skill_script_digest_mismatch",
      reason: `Script ${params.scriptId} integrity hash mismatch`,
    };
  }
  if (params.expectedSha256 && params.expectedSha256.toLowerCase() !== actualSha.toLowerCase()) {
    return {
      ok: false,
      code: "skill_script_expected_hash_mismatch",
      reason: `Script ${params.scriptId} hash changed (${params.expectedSha256.slice(0, 12)} != ${actualSha.slice(0, 12)})`,
    };
  }

  const execAuth = checkSourceReadAuthorized(db, {
    principalId: params.principalId,
    scopeId: params.scopeId,
    sourceType: "skill",
    resourceId: `skill:${params.skillId}`,
    operation: "execute_script",
    scriptId: script.scriptId,
    scriptSha256: actualSha,
  });
  if (!execAuth.ok) {
    return {
      ok: false,
      code: "skill_script_execution_denied",
      reason: `Principal ${params.principalId} lacks independent execute_script permission for ${params.skillId}/${script.scriptId}`,
    };
  }

  return { ok: true, script, version: versionToUse };
}

export function setSkillActiveVersion(
  db: DatabaseSync,
  params: { skillId: string; version: number; actorId: string; now: number },
): { ok: true; skill: SkillRow } | { ok: false; code: string; reason: string } {
  return withImmediateTx(db, () => {
    const ver = db
      .prepare("SELECT * FROM skill_versions WHERE skill_id = ? AND version = ?")
      .get(params.skillId, params.version) as SkillVersionRow | undefined;
    if (!ver) {
      return { ok: false, code: "skill_version_not_found", reason: `Skill ${params.skillId} v${params.version} not found` };
    }
    db.prepare(
      `UPDATE skills
          SET active_version = ?, summary = ?, state = 'ACTIVE', revoked_at = NULL, revoke_reason = NULL, updated_at = ?
        WHERE skill_id = ?`,
    ).run(params.version, ver.summary, params.now, params.skillId);
    writeAuditEvent(db, {
      entityType: "skill",
      entityId: params.skillId,
      eventKey: `activate:${params.skillId}:v${params.version}:${params.now}`,
      eventType: "skill_version_activated",
      occurredAt: params.now,
      details: { version: params.version, actorId: params.actorId },
    });
    const skill = db.prepare("SELECT * FROM skills WHERE skill_id = ?").get(params.skillId) as unknown as SkillRow;
    return { ok: true, skill };
  });
}

export function revokeSkill(
  db: DatabaseSync,
  params: { skillId: string; actorId: string; reason: string; now: number },
): { ok: true; skill: SkillRow } | { ok: false; code: string; reason: string } {
  return withImmediateTx(db, () => {
    const existing = db.prepare("SELECT * FROM skills WHERE skill_id = ?").get(params.skillId) as
      | SkillRow
      | undefined;
    if (!existing) {
      return { ok: false, code: "skill_not_found", reason: `Skill not found: ${params.skillId}` };
    }
    db.prepare(
      `UPDATE skills
          SET state = 'REVOKED', revoked_at = ?, revoke_reason = ?, updated_at = ?
        WHERE skill_id = ?`,
    ).run(params.now, params.reason, params.now, params.skillId);
    writeAuditEvent(db, {
      entityType: "skill",
      entityId: params.skillId,
      eventKey: `revoke:${params.skillId}:${params.now}`,
      eventType: "skill_revoked",
      occurredAt: params.now,
      details: { actorId: params.actorId, reason: params.reason },
    });
    const skill = db.prepare("SELECT * FROM skills WHERE skill_id = ?").get(params.skillId) as unknown as SkillRow;
    return { ok: true, skill };
  });
}
